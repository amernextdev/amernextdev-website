#!/bin/bash

# 1. إعدادات الأمان والاحترافية
# -e: يتوقف السكربت عند حدوث أي خطأ
# -u: يعطي خطأ إذا استخدمت متغير غير معرف
set -eu

# 2. تحديد المتغيرات (لسهولة التعديل مستقبلاً)
PROJECT_DIR="/home/amer/amerdev"
PORT=8800
URL="http://localhost:$PORT"

# 3. وظيفة التنظيف (إغلاق السيرفر عند الضغط على Ctrl+C)
cleanup() {
    echo -e "\n[!] جاري إغلاق السيرفر..."
    # قتل جميع العمليات التابعة لهذا السكربت
    kill 0
}
# تنفيذ الـ cleanup عند الخروج أو المقاطعة
trap cleanup EXIT INT TERM

# 4. التنفيذ
echo "[+] الانتقال إلى المسار: $PROJECT_DIR"
cd "$PROJECT_DIR" || { echo "[-] فشل الدخول للمسار"; exit 1; }

echo "[+] تشغيل سيرفر بايثون على المنفذ $PORT..."
# تشغيل السيرفر في الخلفية (&)
python3 -m http.server $PORT &

# الانتظار قليلاً لضمان عمل السيرفر قبل فتح المتصفح
sleep 2

echo "[+] فتح متصفح كروم على $URL"
# استخدام google-chrome لفتح الرابط
google-chrome "$URL" 2>/dev/null &

# إبقاء السكربت يعمل حتى لا ينتهي ويغلق السيرفر فوراً
wait
